"""副本方案的说话人写法（``speaker_notation``）——方案级内容契约。

三个方案级字段各管一件事，互不推导：

- ``coupling_level``：玩家站在离故事多远的位置（视角、人称禁区与收集职责）；
- ``text_component``：正文怎么画（文本主组件三选一，纯显示投影）；
- ``speaker_notation``：正文怎么写（本模块）。

每个方案**二选一**，选好后是强制规则，方案内不许混用：

- ``tagged``：对话句句首写 ``@说话人@``，分句器解析出结构化 ``speaker``；
- ``literary``：自由文学写法，正文不写任何说话人标记，对话融在叙述里。

结构化 speaker 通道（``DisplayUnit.speaker`` 及其名牌 / 语音 / 角色账本 /
回放消费链）在两种写法下都保留：文学写法只是**正文投影**，不把 speaker 退化成
从中文称呼里猜人。当前 AI 响应只带正文，因此文学写法下 AI 段落没有逐句
speaker（名牌与语音自然安静）；等结构化响应 speaker 接上，显示链无需改动。

本模块只声明记法常量、归一与提示词文本，不反向依赖窗口 / 持久化 / UI。
"""

import re

LITERARY = "literary"
TAGGED = "tagged"

#: 「不许混用」的合法取值；顺序即编辑器里的展示顺序
SPEAKER_NOTATIONS = (LITERARY, TAGGED)
DEFAULT_SPEAKER_NOTATION = TAGGED

SPEAKER_NOTATION_LABELS = {
    LITERARY: "自由文学写法",
    TAGGED: "@说话人@ 标记写法",
}

#: 与 splitter 的显示层解析同一口径：任意位置的 @说话人@（1~12 个非 @ 非换行字符）
SPEAKER_MARKER_RE = re.compile(r"@[^@\n]{1,12}@")


def normalize_speaker_notation(value,
                               default: str = DEFAULT_SPEAKER_NOTATION) -> str:
    """把任意来源的值归一化为合法记法；无法识别时返回 default。"""
    text = str(value or "").strip().lower()
    return text if text in SPEAKER_NOTATIONS else default


def has_speaker_markers(text: str) -> bool:
    """正文里是否出现 ``@说话人@`` 标记（校验「不许混用」用）。"""
    return bool(SPEAKER_MARKER_RE.search(str(text or "")))


# ---------------- 提示词 ----------------

#: 写进系统提示的记法声明：全段生效，不随段落类型切换。
#: 这是「强制规则」的第一层——模型在任何段落都不能改用另一种写法。
NOTATION_DECLARATIONS = {
    TAGGED: (
        "【说话人写法】本方案统一使用「@说话人@」行内标记：两个 @ 之间只写"
        "说话人的名字或称呼（如「李队长」「她」「主角」，不超过 12 字），"
        "绝不写对话内容、引号或标点；凡是人物对话，每一句都以标记开头、"
        "后面直接跟对话内容，不要写「她说：」这类叙述前缀，也不要用引号把"
        "标记和对话一起包住。\n"
        "正确：@李队长@“桥还没塌，先撤居民。”\n"
        "错误（禁止）：她说：「@你好。@」、@“你好。”@、"
        "@李队长@说：「你好。」、他说：「你好。」\n"
        "叙述句不写标记；整段不要改用文学化的对话描写，也不要出现不带标记的对话句。"
    ),
    LITERARY: (
        "【说话人写法】本方案统一使用自由文学写法：对话自然融入叙述，"
        "用行文明示谁在说话即可。正文中禁止出现「@说话人@」标记，"
        "也不要把每句对话机械地拆成带说话人前缀的独立句。"
    ),
}


def notation_declaration(notation) -> str:
    """返回写进系统提示的记法声明（已归一）。"""
    return NOTATION_DECLARATIONS[normalize_speaker_notation(notation)]


